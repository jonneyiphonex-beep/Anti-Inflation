  function getLanguageOptions() {
    return languageOptions.map((language) => ({ ...language }));
  }

  function getDictionary(lang) {
    const locale = String(lang || 'ar').toLowerCase();
    return translations[locale] || translations.en || translations.ar;
  }

  function validateProductInput({ itemName, itemPrice, itemWeight }) {
    const name = String(itemName ?? '').trim();
    const price = Number(itemPrice);
    const weight = Number(itemWeight);

    if (!name || itemName === undefined || itemPrice === undefined || itemWeight === undefined) {
      return { error: 'required', message: 'Please fill in all fields' };
    }

    if (!Number.isFinite(price) || !Number.isFinite(weight) || price <= 0 || weight <= 0) {
      return { error: 'numbers', message: 'Prices and weights must be positive numbers' };
    }

    return { error: null, message: null };
  }

  const api = { getLanguageOptions, getDictionary, validateProductInput, translations };

